func genreOptions() []music.WaveOption {
	out := make([]music.WaveOption, 1, len(waveGenres)+1)
	out[0] = music.WaveOption{Name: "Любой", Seed: "zvuk:genre:any", Group: "genre"}
	for _, g := range waveGenres {
		out = append(out, music.WaveOption{Name: g.label, Seed: "zvuk:genre:" + g.name, Group: "genre"})
	}
	return out
}
func waveGenre(seed string) []map[string]string {
	for _, g := range waveGenres {
		if seed == "zvuk:genre:"+g.name {
			return []map[string]string{{"name": g.name, "type": g.level}}
		}
	}
	return nil
}
